export const GOOD_MEMORY_STANDARD = `# 好记忆的标准（v3）

一条记忆值得留下，要**同时**满足四点：

1. **能迁移**：换个任务、换一天还用得上，不只是对这一件事成立。
2. **查不到**：agent 读代码、读文档，或者报错后重试一次，都得不到这个知识。
3. **改做法**：下一个 agent 知道它以后，会换一种做法（少问一次、少踩一次坑、换一种汇报方式）。
4. **有场景**：写清楚"当…时"用。说不出什么时候用的，等于没写。

## 三类值得记的东西

| 类别 | 是什么 | 例子 |
|---|---|---|
| A 干活偏好 | 用户希望 agent 怎么干活：汇报、语气、工作流、审查习惯 | 说人话；结论写在回复正文里；e2e 不能造假变绿 |
| B 只有人知道的知识 | 业务规则、设计理由、某个决定的背景 | 比率类指标只能建成衍生指标；为什么选了方案 X |
| C 真会反复踩的坑 | 报错看不出原因、会反复浪费时间的坑 | 改了 UI 后要重启 dev server 再跑 e2e，不然测的是旧代码 |

A 类价值最高，而且确认后**每轮常驻注入**。

## 不记什么（用一句话判断）

- 只描述"这次发生了什么"的流水账、日记。
- 报错自己就说明了原因、改一次就好的问题：命令语法、参数写错、要切 JDK 版本。
- 代码里能直接看到的事实：字段、接口、SQL 怎么写。
- 阶段性、临时的用法（"先用 X 体验一下"）。探索中的经验可以留，但要标"探索："。
- 同类的事已经有原则了，就并进原则里，不再单记一条。

## 对照例子（来自 sample30，附用户的点评）

**#17 e2e 造假**
- ✗ 原文："真实依赖（Trino 镜像、connector）上不来时，不要用 fake 执行器顶替……"。只对 Trino 这一个场景成立。
- ✓ 改成：**当**写或跑 e2e 测试时，不能为了变绿伪造环境或数据；优先用真实环境，真起不来就停下，原样汇报报错。（A 类）

**#4 Docker 监控**
- ✗ 原文："Docker 黑盒的 CPU 忙循环和业务错误日志当前不会被主动发现……"。这是系统**现状**，过几天就会变。
- ✓ 改成：**当**设计或评估监控能力时，"能按需查到"不等于"能主动发现"，两者分开设计、分开汇报。（用户的架构偏好，A/B 类）

**#8 指标口径**
- ✗ 原文："导出指标口径时，计算方式要拼成一段人类可读文本合并到单个字段……"。只讲这一张导出表。
- ✓ 改成：**当**给用户看的输出里涉及数据库原始字段时，要翻译成人能读懂的完整说法，不要把一堆内部字段原样摆出来。（A 类）

**#12 耗时口径**
- ✗ 原文："汇报耗时统一用端到端口径……"。用户的意见是：没写什么时候用。
- ✓ 改成：**当**向用户汇报接口或任务耗时时，报端到端时间（提交到最终完成），不只报受理成功的时间。（A 类）

**#21 JDK 11、#5 curl 方括号**
- ✗ 报错本身就说明了原因，agent 重试一次就能修好，直接丢弃。
- ✓ 不记。

## 写法要求

- 正文：一句话，可以照着做，不写"本次 / 刚才 / 日期"。
- 场景：以"当…时"开头，不能只是把正文换个说法。
- 背景（why）：当时发生了什么、用户为什么这样要求。
- 证据：引用户原话或工具输出，必须逐字。父 agent 写给子代理的派活提示不算用户原话。`;
